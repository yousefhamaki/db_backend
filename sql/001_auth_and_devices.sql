-- Migration: auth support on USERS + new DEVICES / REFRESH_TOKENS tables
-- Run via scripts/migrate.js (each statement executed and committed individually,
-- errors for "already exists" objects are tolerated so this is safe to re-run)

-- 1. USERS: make USER_ID usable as a real foreign key target, add auth columns
ALTER TABLE USERS MODIFY (USER_ID NUMBER NOT NULL);
ALTER TABLE USERS ADD CONSTRAINT UQ_USERS_USER_ID UNIQUE (USER_ID);
ALTER TABLE USERS ADD (EMAIL_VERIFIED CHAR(1) DEFAULT 'N' NOT NULL);
ALTER TABLE USERS ADD (VERIFICATION_TOKEN VARCHAR2(255));
ALTER TABLE USERS ADD (VERIFICATION_EXPIRY DATE);

-- 2. DEVICES: devices registered per user, capped by their plan's NO_OF_USERS
CREATE TABLE DEVICES (
  DEVICE_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ID             NUMBER NOT NULL,
  DEVICE_NAME         VARCHAR2(100),
  DEVICE_IDENTIFIER   VARCHAR2(255) NOT NULL,
  PLATFORM            VARCHAR2(50),
  REGISTERED_AT        DATE DEFAULT SYSDATE NOT NULL,
  LAST_SEEN           DATE,
  STATUS              VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  CONSTRAINT FK_DEVICES_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
  CONSTRAINT UQ_DEVICE_USER_IDENT UNIQUE (USER_ID, DEVICE_IDENTIFIER)
);

-- 3. REFRESH_TOKENS: server-side revocable refresh tokens (hash only, never raw token)
CREATE TABLE REFRESH_TOKENS (
  TOKEN_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ID      NUMBER NOT NULL,
  TOKEN_HASH   VARCHAR2(255) NOT NULL,
  EXPIRES_AT   DATE NOT NULL,
  REVOKED      CHAR(1) DEFAULT 'N' NOT NULL,
  CREATED_AT   DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT FK_REFRESH_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);
