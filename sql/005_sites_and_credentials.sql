-- Migration: split CONNECTIONS into SITES (1) -> SITE_CREDENTIALS (many).
-- The old CONNECTIONS table is left untouched as a backup; drop it manually once verified.

CREATE TABLE SITES (
  SITE_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ID        NUMBER NOT NULL,
  SITE_NAME      VARCHAR2(50) NOT NULL,
  IP             VARCHAR2(15),
  PORT           VARCHAR2(4) DEFAULT '1521',
  SERVICE_NAME   VARCHAR2(20),
  CONSTRAINT FK_SITES_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
  CONSTRAINT UQ_SITES_USER_NAME UNIQUE (USER_ID, SITE_NAME)
);

CREATE TABLE SITE_CREDENTIALS (
  CREDENTIAL_ID  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SITE_ID        NUMBER NOT NULL,
  USER_NAME      VARCHAR2(30) NOT NULL,
  PASSWORD       VARCHAR2(255),
  CONSTRAINT FK_CREDENTIALS_SITE FOREIGN KEY (SITE_ID) REFERENCES SITES(SITE_ID) ON DELETE CASCADE,
  CONSTRAINT UQ_CREDENTIALS_SITE_USER UNIQUE (SITE_ID, USER_NAME)
);

-- Sites: every legacy row, except "<name>_API" rows whose base site "<name>" exists for the
-- same user with identical IP / PORT / SERVICE_NAME (those become extra credentials of the base site).
INSERT INTO SITES (USER_ID, SITE_NAME, IP, PORT, SERVICE_NAME)
SELECT c.USER_ID, c.SITE, c.IP, c.PORT, c.SERVICE_NAME
FROM CONNECTIONS c
WHERE NOT (
  c.SITE LIKE '%\_API' ESCAPE '\'
  AND EXISTS (
    SELECT 1 FROM CONNECTIONS b
    WHERE b.USER_ID = c.USER_ID
      AND LOWER(b.SITE) = LOWER(SUBSTR(c.SITE, 1, LENGTH(c.SITE) - 4))
      AND NVL(b.IP, '~') = NVL(c.IP, '~')
      AND NVL(b.PORT, '~') = NVL(c.PORT, '~')
      AND NVL(b.SERVICE_NAME, '~') = NVL(c.SERVICE_NAME, '~')
  )
);

-- Credentials: each legacy row's username/password attaches to its own site, or to the base site it was folded into.
INSERT INTO SITE_CREDENTIALS (SITE_ID, USER_NAME, PASSWORD)
SELECT s.SITE_ID, c.USER_NAME, c.PASSWORD
FROM CONNECTIONS c
JOIN SITES s
  ON s.USER_ID = c.USER_ID
 AND (
      s.SITE_NAME = c.SITE
   OR (
        c.SITE LIKE '%\_API' ESCAPE '\'
    AND LOWER(s.SITE_NAME) = LOWER(SUBSTR(c.SITE, 1, LENGTH(c.SITE) - 4))
    AND NVL(s.IP, '~') = NVL(c.IP, '~')
    AND NVL(s.PORT, '~') = NVL(c.PORT, '~')
    AND NVL(s.SERVICE_NAME, '~') = NVL(c.SERVICE_NAME, '~')
   )
 )
WHERE c.USER_NAME IS NOT NULL
ORDER BY c.CONNECTION_ID;
